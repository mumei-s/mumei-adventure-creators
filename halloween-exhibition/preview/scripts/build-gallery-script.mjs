import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const builder='scripts/build-gallery-script.mjs';
const output='gallery-entry.js';
const manifestPath='gallery-script-manifest.json';
const esbuildVersion='0.25.12';
const releasePrefix='20261019-fast2';
export const galleryEntrySources=['./theater.js','./pwa.js','./castle-counter-bootstrap.js','./gallery-panels.js'];
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');

function localPath(directory,relative){
 if(typeof relative!=='string'||!relative||path.isAbsolute(relative)||relative.split(/[\\/]/).includes('..'))throw Error('Invalid gallery script input path');
 return path.join(directory,relative);
}
async function fingerprint(directory,relative){
 const bytes=await readFile(localPath(directory,relative));
 return{path:relative,bytes:bytes.length,sha256:digest(bytes)};
}
const assetReferences=(html,name)=>[...html.matchAll(new RegExp(`(?:href|src)="(\\./${name.replaceAll('.','\\.')}(?:\\?[^\"]*)?)"`,'g'))].map(match=>match[1]);
function checkAssetReferences(html,manifest){
 for(const asset of [manifest.output,manifest.styles]){
  const expected=`./${asset.path}?v=${releasePrefix}-${asset.sha256.slice(0,12)}`;
  const references=assetReferences(html,asset.path);
  if(!references.length||references.some(reference=>reference!==expected))throw Error(`index.html has an outdated ${asset.path} URL. Run npm run build:script.`);
 }
}
async function updateAssetReferences(directory,manifest){
 const filename=path.join(directory,'index.html');
 const original=await readFile(filename,'utf8');
 let html=original;
 for(const asset of [manifest.output,manifest.styles]){
  const references=assetReferences(html,asset.path);
  if(!references.length)throw Error(`index.html does not reference ${asset.path}`);
  const expected=`./${asset.path}?v=${releasePrefix}-${asset.sha256.slice(0,12)}`;
  for(const reference of new Set(references))html=html.replaceAll(`="${reference}"`,`="${expected}"`);
 }
 checkAssetReferences(html,manifest);
 if(html!==original)await writeFile(filename,html);
}

/** Hash verification deliberately needs only Node, including on publishing CI. */
export async function checkGalleryScript({directory=root}={}){
 const manifest=JSON.parse(await readFile(localPath(directory,manifestPath),'utf8'));
 if(manifest.schemaVersion!==1||manifest.builder!==`esbuild@${esbuildVersion}`||manifest.output?.path!==output||manifest.styles?.path!=='gallery-styles.css'||!Array.isArray(manifest.inputs)||!manifest.inputs.length)throw Error('Invalid gallery script manifest');
 const paths=manifest.inputs.map(input=>input.path);
 if(new Set(paths).size!==paths.length||!paths.includes(builder)||!paths.includes('data/archive.json'))throw Error('Incomplete gallery script inputs');
 for(const expected of [...manifest.inputs,manifest.output,manifest.styles]){
  const actual=await fingerprint(directory,expected.path);
  if(actual.sha256!==expected.sha256||actual.bytes!==expected.bytes)throw Error(`${expected.path} changed. Run npm run build:script.`);
 }
 checkAssetReferences(await readFile(path.join(directory,'index.html'),'utf8'),manifest);
 return manifest;
}

async function importBuilder(){
 try{return await import('esbuild');}
 catch(error){
  // A development tool path may be supplied without copying dependencies into
  // the website. Normal npm installs always resolve the pinned local package.
  if(!process.env.ATELIER_ESBUILD_PATH)throw Error('Run npm ci before npm run build:script.',{cause:error});
  return import(pathToFileURL(path.resolve(process.env.ATELIER_ESBUILD_PATH)).href);
 }
}

export async function buildGalleryScript(){
 const esbuild=await importBuilder();
 if(esbuild.version!==esbuildVersion)throw Error(`Expected esbuild ${esbuildVersion}; found ${esbuild.version}`);
 const archive=JSON.parse(await readFile(path.join(root,'data/archive.json'),'utf8'));
 const {validateArchive}=await import('../data-model.js');
 validateArchive(archive);
 const result=await esbuild.build({
  absWorkingDir:root,
  stdin:{contents:galleryEntrySources.map(source=>`import ${JSON.stringify(source)};`).join('\n'),resolveDir:root,sourcefile:'gallery-entry.virtual.js',loader:'js'},
  outfile:path.join(root,output),bundle:true,minify:true,target:'es2020',format:'esm',platform:'browser',charset:'utf8',legalComments:'none',metafile:true,write:false,
  define:{__ATELIER_ARCHIVE__:JSON.stringify(archive)},
  banner:{js:'/* Generated by npm run build:script. Edit source modules, then regenerate. */'},
  plugins:[{name:'defer-optional-modules',setup(build){build.onResolve({filter:/.*/},args=>args.kind==='dynamic-import'?{path:args.path,external:true}:undefined);}}],
 });
 const script=result.outputFiles.find(file=>path.resolve(file.path)===path.join(root,output));
 if(!script)throw Error('Gallery script output was not produced');
 const sources=Object.keys(result.metafile.inputs).filter(input=>!input.endsWith('gallery-entry.virtual.js')&&!input.startsWith('<')).map(input=>input.split('?')[0]);
 const inputPaths=[...new Set([...sources,'data/archive.json',builder,'package.json','package-lock.json'])].sort();
 const inputs=await Promise.all(inputPaths.map(source=>fingerprint(root,source)));
 const imports=result.metafile.outputs[output]?.imports||Object.values(result.metafile.outputs)[0]?.imports||[];
 if(imports.some(item=>item.kind!=='dynamic-import'))throw Error('Gallery startup still has an external static dependency');
 const manifest={schemaVersion:1,builder:`esbuild@${esbuildVersion}`,entrySources:galleryEntrySources,inputs,output:{path:output,bytes:script.contents.length,sha256:digest(script.contents)},styles:await fingerprint(root,'gallery-styles.css'),imports};
 await writeFile(path.join(root,output),script.contents);
 await writeFile(path.join(root,manifestPath),`${JSON.stringify(manifest,null,2)}\n`);
 await updateAssetReferences(root,manifest);
 return manifest;
}

const invoked=process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url);
if(invoked){
 if(process.argv.includes('--check')){await checkGalleryScript();console.log('Gallery script bundle is current.');}
 else{const manifest=await buildGalleryScript();console.log(`Wrote ${manifest.output.path} (${manifest.output.bytes} bytes; ${manifest.inputs.length} inputs).`);}
}
