import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

// Every source and output lives in the same directory: relative CSS URLs retain
// their exact browser resolution. Preserve source order and every declaration.
const root=new URL('../',import.meta.url);
export async function buildGalleryStyles(){
 const sources=JSON.parse(await readFile(new URL('gallery-style-sources.json',root),'utf8'));
 if(!Array.isArray(sources)||!sources.length||new Set(sources).size!==sources.length)throw Error('Invalid stylesheet source order');
 const chunks=['/* Generated by npm run build:styles. Edit the source CSS, then regenerate. */\n'];
 for(const source of sources){
  if(!/^\.\/[a-z0-9-]+\.css(?:\?v=[a-z0-9-]+)?$/.test(source))throw Error(`Stylesheet must share the bundle directory: ${source}`);
  const css=await readFile(new URL(source.split('?')[0],root),'utf8');
  // These directives have position-sensitive semantics; do not silently move them.
  if(/@(import|charset|namespace)\b/i.test(css))throw Error(`Unsupported position-sensitive directive in ${source}`);
  chunks.push(`\n/* Source: ${source} */\n${css}\n`);
 }
 return chunks.join('');
}
const invoked=process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url);
if(invoked){
 const expected=await buildGalleryStyles(),target=new URL('gallery-styles.css',root);
 if(process.argv.includes('--check')){
  if(await readFile(target,'utf8')!==expected)throw Error('gallery-styles.css is stale. Run npm run build:styles.');
  console.log('Gallery stylesheet bundle is current.');
 }else{await writeFile(target,expected);console.log(`Wrote gallery-styles.css (${Buffer.byteLength(expected)} bytes).`);}
}
