test('HTML preloads and loads assets using their current content hashes',async()=>{
 const manifest=await checkGalleryScript();
 const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
 const styles=await readFile(new URL('../gallery-styles.css',import.meta.url));
 const stylesHash=createHash('sha256').update(styles).digest('hex');
 const scriptURL=`./gallery-entry.js?v=20261019-fast2-${manifest.output.sha256.slice(0,12)}`;
 const styleURL=`./gallery-styles.css?v=20261019-fast2-${stylesHash.slice(0,12)}`;
 assert.ok(html.includes(`rel="modulepreload" href="${scriptURL}"`));
 assert.ok(html.includes(`src="${scriptURL}"`));
 assert.ok(html.includes(`href="${styleURL}"`));
 assert.equal(manifest.styles.sha256,stylesHash);
});

test('dependency-free check detects changed source and changed generated output',async()=>{
 const directory=await mkdtemp(path.join(os.tmpdir(),'gallery-script-check-'));
 try{
  const inputNames=['scripts/build-gallery-script.mjs','data/archive.json'];
  async function write(relative,contents){await mkdir(path.dirname(path.join(directory,relative)),{recursive:true});await writeFile(path.join(directory,relative),contents);}
  async function fingerprint(relative){const bytes=await readFile(path.join(directory,relative));return{path:relative,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')};}
  for(const input of inputNames)await write(input,'original');
  await write('gallery-entry.js','built');
  await write('gallery-styles.css','style');
  const manifest={schemaVersion:1,builder:'esbuild@0.25.12',inputs:await Promise.all(inputNames.map(fingerprint)),output:await fingerprint('gallery-entry.js'),styles:await fingerprint('gallery-styles.css')};
  await write('index.html',`<link href="./gallery-styles.css?v=20261019-fast2-${manifest.styles.sha256.slice(0,12)}"><script src="./gallery-entry.js?v=20261019-fast2-${manifest.output.sha256.slice(0,12)}"></script>`);
  await write('gallery-script-manifest.json',JSON.stringify(manifest));
  await checkGalleryScript({directory});
  await write('data/archive.json','changed');
  await assert.rejects(checkGalleryScript({directory}),/data\/archive.json changed/);
  await write('data/archive.json','original');
  await write('gallery-entry.js','changed output');
  await assert.rejects(checkGalleryScript({directory}),/gallery-entry.js changed/);
 }finally{await rm(directory,{recursive:true,force:true});}
});
