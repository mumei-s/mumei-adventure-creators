function paletteName(value) {
  return String(value ?? '').trim().replace(/\s+/gu, ' ');
}

function limitedPalette(value) {
  const name = paletteName(value).replace(/\s/gu, '');
  if (/^(?:モノクロ(?:ーム)?|monochrome|白黒)$/iu.test(name)) {
    return '黒・白・灰のみ。白い逆光と灰の中間調、黒い影で描き、有彩色の差し色を加えない。';
  }
  if (name === '墨一色') {
    return '黒い墨と紙の白のみ。墨の濃淡と紙の白で深い影から鋭い逆光まで描く。色の光や金色を加えず、描線とセル影の技法を保つ。';
  }
  if (name === '金と黒の二色' || name === '金×黒') {
    return '金と黒の二色のみ。最も明るい金を逆光と点光、深い黒を影に使う。白い逆光も金へ翻訳し、白・紫・青などの別色を加えない。';
  }
  if (name === '黒と白と朱の三色') {
    return '黒・白・朱の三色のみ。白い逆光と黒い影を対比し、朱は画面の10%以下の小さな焦点へ使う。他の有彩色を反射光にも加えない。';
  }
  if (/^(?:セピア|sepia)$/iu.test(name)) {
    return '褐色の濃淡と紙の明部のみ。最も明るい紙色の逆光と深い褐色の影を対比し、青・紫・赤などの差し色を加えない。';
  }
  if (name === '焦茶×シアン光' || name === '夜の二色印刷') {
    return '焦茶とシアンの二つの色相のみ。焦茶の深い影と明るいシアンの光を対比し、白い逆光も許可されたシアンの明部へ翻訳する。';
  }
  if (/(?:二色|三色|限定色)/u.test(name)) {
    return '指定された許可色とその明度差だけを使う。逆光は許可色の最明部、影は最暗部へ翻訳し、指定外の白や寒色を追加しない。';
  }
  return '';
}

export function isCrystalAnimeLimitedPalette(value) {
  return Boolean(limitedPalette(value));
}

export function crystalAnimePalette(value, { noPerson = false } = {}) {
  const name = paletteName(value);
  const limited = limitedPalette(name);
  const contrast = '色相はこの配色に従い、選択色を深めた明快な影面と小さく鋭い光の間に、強い局所的な明度差を保つ。淡色中心でも最暗部を残す。';
  if (limited) {
    const identity = noPerson
      ? '景物・建築・自然素材の元の色も許可色と明度差へ翻訳し、形・構造・模様・明暗の関係で識別できる特徴を保つ。'
      : '髪・肌・瞳を含む全ての元の色を許可色と明度差へ翻訳し、輪郭・配置・形・模様・明暗の関係で同じキャラクターと分かる特徴を保つ。';
    return '限定配色「' + name + '」：' + limited + identity + contrast + '配色名だけから物体や別の画材表現を追加しない。';
  }

  let hues;
  if (name === '参照画像の色を生かす') {
    hues = '主参照から実際の主色・副色・差し色を採り、選択舞台の中で光と影の色を設計する。';
  } else if (!name || /^(?:自動|指定なし|おまかせ)$/u.test(name)) {
    hues = '主題に合う色を選び、澄んだ寒色寄りの影と白い逆光を基本にする。';
  } else {
    const selectedHues = Object.prototype.hasOwnProperty.call(paletteHues, name) ? paletteHues[name] : name;
    hues = '選択配色「' + name + '」の色相は「' + selectedHues + '」。基調と影をこの色域で設計し、分散・干渉の光学色は透明層の中だけに置く。';
  }
  const identity = noPerson
    ? '景物・物体・空間へ選択色を配分し、参照がある場合は形・構造・模様の特徴を保つ。'
    : '人物の髪・瞳・肌の基礎色はキャラクター参照を保ち、透明色層の内部に淡い識別色として使う。顔と身体は背景の形が透ける澄んだ彩色へ変換し、普通の不透明な肌を残さない。衣装・背景・反射光へ選択色を配分し、反射光で固有色を塗り替えない。';
  return hues + identity + contrast + opticalColors({medium:CRYSTAL_ANIME,palette:value},{noPerson}).instruction + '白い点光は狭い範囲に置き、画面全体を白く飛ばさない。色名は色相だけを指定し、題材・物体・技法を追加しない。';
}

