function render(text, noPerson, policy) {
 let resolved = text.replace(/\{(surface|focal|bright|dark|interference)\}/g, (_, key) => {
  if (key === 'bright') return policy.bright;
  if (key === 'dark') return policy.restricted ? policy.dark + 'の深い濃淡' : '選択色を深めた有彩色の暗部';
  if (key === 'interference') return policy.restricted ? policy.allowed + 'の明度差による細い干渉縁' : 'シアン・菫・マゼンタ・淡金へ角度で色が切り替わる干渉帯';
  return slots[key][noPerson ? 1 : 0];
 });
 // Fixed-color techniques have their own policy; otherwise paper, ink and optical
 // highlights also obey an explicitly restricted palette. Negative examples such
 // as "白い霞を避ける" are left intact because they do not add a drawing color.
 if (policy.restricted && !['monochrome','cyanotype'].includes(policy.mode)) {
  resolved = resolved.replace(/(?:紙の|下地の)?白または許可された(?:下地の)?最明色|白または許可色の最明色/g,policy.bright)
   .replace(/紙の白/g,policy.bright)
   .replace(/紙の広い白/g,policy.bright)
   .replace(/白抜き/g,policy.bright+'の抜き')
   .replace(/白い反射/g,policy.bright+'の反射')
   .replace(/白い面/g,policy.bright+'の面')
   .replace(/白い領域/g,policy.bright+'の領域')
   .replace(/白を挟む/g,policy.bright+'を挟む')
   .replace(/白枠/g,policy.bright+'の枠')
   .replace(/白黒/g,policy.allowed+'の明暗')
   .replace(/黒ベタ/g,policy.dark+'のベタ')
   .replace(/黒い影/g,policy.dark+'の影')
   .replace(/濃い黒/g,policy.dark)
   .replace(/黒を締め/g,policy.dark+'を締め');
 }
 return resolved;
}
