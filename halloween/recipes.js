export function recipeFor(key,value){
 const world=(key==='palette'?colorWorlds:key==='medium'?luminousMedia:[]).find(x=>x.value===value);
 if(world)return {key,value,file:world.file,text:world.text};
 const sample=individualSamples[key+'\u0000'+value];
 if(!sample)return {key,value,file:null,text:'選択した「'+value+'」を優先。添付や自由入力の条件を具体的に読む。'};
 const matching=traits.filter(([rx])=>rx.test(value)).map(([,text])=>text);
 return {key,value,file:sample.file,text:(key==='medium'?lookFor(key,value).detail+'。':'')+(matching[0]||({theme:'この作例は物語・世界観の参照。人物の顔や構図を流用せず、指定の場面を新しく設計する。',costume:'この作例は衣装の構造・素材・装飾の参照。顔・表情・ポーズ・画風は他の指定を優先する。',mood:'この作例は感情・表情または顔角度の参照。人物の顔立ち・衣装・構図を写さない。',place:'この作例は舞台の構造・奥行き・空気感の参照。画風や被写体は指定へ合わせる。',palette:'この作例は色の組み合わせ・配分の参照。人物や背景モチーフを流用しない。',design:'この作例は形式・余白・文字の階層の参照。顔・画風・場面を流用しない。',medium:'この作例の描線・色面・陰影・画材の手触りを全体で再現する。参照人物の顔立ち以外の写真の質感を引きずらない。'}[key]||'選択した特徴だけを作品へ反映する。'))};
}
export const sampleKeys=['medium','design','theme','costume','mood','place','palette'];
export function selectedRecipes(values){return sampleKeys.map(key=>recipeFor(key,values[key]));}
