import assert from 'node:assert/strict';
import {File} from 'node:buffer';
import {buildIndividualSelectionReferenceZip} from '../selection-references.js';
const manifest={name:'selection-references.jpg',conditions:[{key:'medium',value:'発光幻想アニメ',label:'画風'},{key:'size',value:'square',label:'サイズ'}],items:[]};
const image=(name,role)=>({name,role,file:new File(['unchanged '+name],name,{type:'image/png'})});
const identity=image('person.png','identity'),support=image('prop.png','support'),avoid=image('previous.png','avoid'),style=image('style.png','style-preset');
const composeIndividualPrompt=m=>'発光幻想アニメ square\n'+m.references.map(r=>r.name+' '+r.role).join('\n');
const build=extra=>buildIndividualSelectionReferenceZip({manifest,styleReferences:[style],composeIndividualPrompt,...extra},{FileClass:File});
const result=await build({identityReferences:[support,avoid,identity]});
assert.deepEqual(result.files.map(f=>f.name),['person.png','prop.png','previous.png','style.png']);
assert.equal(result.manifest.counts.identity,1);assert.equal(result.manifest.counts.support,1);assert.equal(result.manifest.counts.avoid,1);
assert.match(result.prompt,/prop\.png：補助資料/);assert.match(result.prompt,/previous\.png：似せない前作/);
assert.doesNotMatch(result.prompt,/prop\.png：選択作風|previous\.png：選択作風/);
assert.match(result.prompt,/previous\.png：[^\n]+採用元にしない/);
for(const f of result.files)assert.equal(await f.text(),'unchanged '+f.name);
const pending={name:'ChatGPTへ直接添付する主参照',role:'identity'};
const direct=await build({pendingReferences:[pending]});
assert.equal(direct.manifest.counts.identity,0);assert.equal(direct.manifest.counts.pendingIdentity,1);
assert.equal(direct.files.length,1);assert.equal(direct.manifest.references[0].attached,false);
assert.match(direct.prompt,/必要な主参照が未添付なら生成を止めて添付を求める/);
assert.match(direct.prompt,/ZIPには未収録・別途添付/);
const missing=await build({pendingReferences:[{...pending,name:'lost-person.png'}, {name:'lost-avoid.png',role:'avoid'}]});
assert.match(missing.prompt,/lost-avoid\.png：似せない前作/);
await assert.rejects(build({identityReferences:[pending]}),/ファイルを確認/);
await assert.rejects(build({pendingReferences:[{name:'style-missing.png',role:'style-preset'}]}),/役割を確認/);
await assert.rejects(build({identityReferences:[identity],pendingReferences:[{name:identity.name,role:'identity'}]}),/重複/);
console.log('Individual export: identity/support/avoid roles, source bytes, identity-first order, direct/missing-image descriptors and validation passed.');

const limit=await build({identityReferences:[1,2,3,4].map(i=>image('support-'+i+'.png','support')),pendingReferences:[pending]});
assert.equal(limit.files.length,5);assert.equal(limit.manifest.counts.attached,5);assert.equal(limit.manifest.counts.pendingIdentity,1);assert.equal(limit.manifest.execution.requiredAttachmentCount,6);assert.equal(limit.manifest.execution.canUseObservedSingleCall,false);
