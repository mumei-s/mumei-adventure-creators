import {photoReconstruction} from './photo-design.js?v=28.4.4';
export function styleFidelity(condition,{noPerson=false,values={}}={}){
 const regions=noPerson?'主景・物体・構造・背景':'顔の輪郭・目鼻口・髪・身体・衣装・背景';
 const photo=photoReconstruction(condition.value,{noPerson,values});
 if(photo)return [
  '【作風を作品全域へ】選択作風「'+condition.value+'」で'+regions+'を、実物の被写体を同じカメラで撮影した一つの像として再構成する。参照の識別特徴を保ち、イラストの描線や平たいセル色を撮影表現として残さない。',
  ...photo.sections.map(section=>section.text),
  'この作風の見える特徴：'+condition.checks.join(' / '),
  (noPerson?'主景の輪郭・構造・材料の境界':'顔の識別点と選んだ動作のシルエット')+'を、指定カメラから見える範囲で判読できる撮影像へ整える。主題の見やすさを理由に画角やポーズを変更しない。',
  '主役と背景を同じ実照明、材質の反射、連続した露光階調、レンズ遠近と焦点でつなぐ。写真化は参照へ粒子やぼけを重ねる加工だけで済ませず、指定の画角・ポーズ・主題を保って成立させる。'+(condition.value==='発光幻想リアル'?'画面に見える素材内部の幻想色光を、広い深暗部、透明な色光の層、小面積の強い光と鋭い最明部として同じ撮影空間へ連続させる。実照明や場面光源の記述を理由に、この色光の密度を弱めない。':''),
  '完成画像そのものを確認し、主役と背景の両方が選択した写真の光学像と実物の材質になっているか照合する。未確認の写真変換を達成したと断言しない。'
 ];
 const reduced=/禅画|書と墨の抽象|線画|ピクセルアート|ベクターグラフィック|フラットイラスト|ローポリゴン|ボクセル|フラクタルアート|抽象表現|キュビスム|構成主義|ポップアート|アウトサイダーアート|ミニマリズム/.test(condition.value);
 const focus=noPerson?'主景の輪郭・構造・材料の境界':'顔の識別点と選んだ動作のシルエット';
 return [
  '【作風を作品全域へ】選択作風「'+condition.value+'」で'+regions+'を最初から描き起こす。参照から固定するのは識別特徴の組合せ。画材・描線・陰影・材質はこの作風へ翻訳する。',
  'この作風の見える特徴：'+condition.checks.join(' / '),
  '主役と背景を一つの空間と同じ制作工程でつなぐ。顔だけ写真、背景だけ絵画、衣装だけCGの混在へ戻さない。選択した立体・写真・コラージュの技法では、その技法自体が指定する素材と工程で全域を統一する。',
  (noPerson?'指定した視点・距離は、主景の重なりと大小、地形や物体の支持を選択技法へ翻訳して描く。人物の顔や手・身体動作を追加しない。':'指定した俯瞰・煽り・手前への動作は、輪郭の重なりと大小、支持点まで実際に描く。')+focus+'を判読できる形に整える。'+(reduced?'線・筆の配置、色面・画素・立体要素の重なり、抜きと余白で前後を示す。写真風の陰影やぼけ、細密描写を一律に追加しない。':'近景・主役・遠景の形と明暗を選択技法で描き分ける。')+'指定のない画角やポーズには変更しない。',
  '作り込みは選択技法の特徴へ配分する。'+(noPerson?'細密な作画では景物の継ぎ目、部材と植生の構造、反射先、表面の尺度を描き分ける。':'細密な作画では瞳の色層、髪の束とほつれ、衣服の裁断と留め具、景物の構造と反射先を描き分ける。')+'墨・木版・平面・最小限の図案では筆圧、彫り、線の太さ、色面、抜きと余白の精度で同じ完成度を作る。単に光の粒や小物を増やして仕上げを代用しない。',
  '完成画像そのものを確認し、主役と背景の両方に上の特徴が見えるか照合する。未確認の画風を再現できたと断言しない。'
 ];
}
