const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE||'/usr/bin/chromium',args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:390,height:844}});
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://slamzhgsawfnmwlejgqp.supabase.co/**',route=>{const view=new URL(route.request().url()).searchParams.get('view');return route.fulfill({status:200,headers:{'access-control-allow-origin':'*'},json:view==='list'?{floors:12,perFloor:12,rooms:[]}:{residents:[]}});});
 await page.goto('http://127.0.0.1:4173/tower/?source=pwa',{waitUntil:'networkidle'});
 const cdp=await context.newCDPSession(page);
 const result=await cdp.send('Page.getAppManifest');
 assert.deepEqual(result.errors,[]);
 const manifest=JSON.parse(result.data);assert.equal(manifest.display,'standalone');assert.equal(manifest.scope,'../');assert.equal(manifest.start_url,'./?source=pwa');
 await page.click('[data-space="lobby"]');
 await page.waitForSelector('#entrance-doors:not([hidden])');
 assert.equal(await page.locator('#shared-dialog').getAttribute('open'),null);
 await page.waitForSelector('#shared-dialog[open]');
 await page.locator('#shared-exit').click();
 await page.waitForSelector('#entrance-doors:not([hidden])');
 assert.equal(await page.locator('#shared-dialog').getAttribute('open'),null);
 await page.waitForURL('**/diorama-city/?arrival=tower');
 assert.ok(await page.locator('#city-view').isVisible());
 await page.goto('http://127.0.0.1:4173/tower/?from=diorama',{waitUntil:'networkidle'});
 await page.waitForSelector('#shared-dialog[open]');
 assert.match(await page.locator('#shared-title').textContent(),/エントランス/);
 await page.locator('#shared-back').click();assert.equal(await page.locator('#shared-dialog').getAttribute('open'),null);
 assert.deepEqual(errors,[]);
 console.log('PASS Chrome PWA manifest, start route, visible entry/exit doors, city round trip and Back');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
